// Package docs generates derived README and .env.example artifacts.
package docs

import (
	"fmt"
	"sort"
	"strings"

	"iacpack/internal/domain/ir"
	"iacpack/internal/domain/plan"
)

// README generates docs/README.md content (LF).
func README(d ir.Deployment, g plan.Graph) string {
	var b strings.Builder
	b.WriteString("# ")
	b.WriteString(d.Project.Name)
	b.WriteString("\n\n")
	b.WriteString("<!-- Generated by iacpack — derived, non-authoritative. -->\n\n")
	b.WriteString(fmt.Sprintf("- Version: `%s`\n", d.Project.Version))
	b.WriteString(fmt.Sprintf("- Mode: `%s`\n", d.Mode))
	b.WriteString(fmt.Sprintf("- Profile: `%s`\n", d.Profile))
	b.WriteString(fmt.Sprintf("- Deployment hash: `%s`\n\n", d.SemanticHash))
	if d.Project.Description != "" {
		b.WriteString(d.Project.Description)
		b.WriteString("\n\n")
	}

	b.WriteString("## Requirements\n\n")
	b.WriteString("- Docker Engine with Compose plugin (`docker compose`)\n")
	b.WriteString("- Explicit deploy parameters and secret files at apply time\n")
	b.WriteString("- This artifact tree as the deployment package (do not treat it as authoring source)\n\n")

	b.WriteString("## Parameters (non-secret)\n\n")
	pids := sortedKeys(d.Parameters)
	if len(pids) == 0 {
		b.WriteString("_None declared._\n\n")
	} else {
		for _, id := range pids {
			p := d.Parameters[id]
			b.WriteString(fmt.Sprintf("- `%s` (%s, phase=%s)", id, p.Type, p.Phase))
			if p.Description != "" {
				b.WriteString(": ")
				b.WriteString(p.Description)
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	b.WriteString("## Secrets (declarations only)\n\n")
	sids := sortedKeys(d.Secrets)
	if len(sids) == 0 {
		b.WriteString("_None declared._\n\n")
	} else {
		b.WriteString("Provide each secret as a file at apply (`--secret-file id=/path`). Values are never stored in this package.\n\n")
		for _, id := range sids {
			s := d.Secrets[id]
			req := "required"
			if !s.Required {
				req = "optional"
			}
			b.WriteString(fmt.Sprintf("- `%s` (%s, delivery=%s)", id, req, s.Delivery))
			if s.Description != "" {
				b.WriteString(": ")
				b.WriteString(s.Description)
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	b.WriteString("## Services\n\n")
	for _, id := range sortedKeys(d.Services) {
		svc := d.Services[id]
		b.WriteString(fmt.Sprintf("### `%s`\n\n", id))
		b.WriteString(fmt.Sprintf("- Image: `%s`\n", svc.Image))
		if len(svc.Ports) > 0 {
			b.WriteString("- Ports:\n")
			for _, p := range svc.Ports {
				host := "(none)"
				if p.Host != nil {
					if p.Host.Literal != nil {
						host = fmt.Sprintf("%d", *p.Host.Literal)
					} else if p.Host.Parameter != "" {
						host = "parameter:" + p.Host.Parameter
					}
				}
				b.WriteString(fmt.Sprintf("  - container `%d` → host `%s` (%s) bind `%s`\n", p.Container, host, p.Protocol, p.Bind))
			}
		}
		b.WriteString("\n")
	}

	b.WriteString("## Lifecycle tasks\n\n")
	tids := sortedKeys(d.Tasks)
	if len(tids) == 0 {
		b.WriteString("_None declared._\n\n")
	} else {
		for _, id := range tids {
			t := d.Tasks[id]
			b.WriteString(fmt.Sprintf("- `%s` phase=`%s` rerun=`%s`\n", id, t.Phase, t.Rerun))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Action graph\n\n")
	b.WriteString("See `docs/architecture.mmd` (Mermaid). Deployment hash keys `oncePerDeployment` tasks.\n")
	b.WriteString("Manual tasks (`rerun: manual`) run only via `iacpack task run` (Compose profile `iacpack-task`).\n\n")
	b.WriteString(fmt.Sprintf("- Actions: %d\n- Edges: %d\n\n", len(g.Actions), len(g.Edges)))

	b.WriteString("## Update / destroy safety\n\n")
	b.WriteString("- Named volumes default to `retention: retain` and are not deleted by ordinary destroy.\n")
	b.WriteString("- Destructive volume deletion requires explicit flags and confirmation.\n")
	b.WriteString("- Pre-existing external networks/volumes are never created or removed by iacpack.\n\n")

	b.WriteString("## Recovery\n\n")
	b.WriteString("Use `iacpack status` / `iacpack resume` against the verified package after a partial apply. Do not hand-edit generated Compose as the source of truth.\n")
	return b.String()
}

// EnvExample generates config/.env.example for non-secret deploy parameters.
func EnvExample(d ir.Deployment) string {
	var b strings.Builder
	b.WriteString("# Generated by iacpack — placeholders only. Never commit a populated .env.\n")
	ids := sortedKeys(d.Parameters)
	wrote := false
	for _, id := range ids {
		p := d.Parameters[id]
		if p.Phase != "deploy" {
			continue
		}
		wrote = true
		key := envKey(id)
		val := ""
		if p.Default != nil {
			val = fmt.Sprint(p.Default)
		} else {
			val = "<set-" + id + ">"
		}
		if p.Description != "" {
			b.WriteString("# " + strings.ReplaceAll(p.Description, "\n", " ") + "\n")
		}
		b.WriteString(key)
		b.WriteByte('=')
		b.WriteString(val)
		b.WriteByte('\n')
	}
	if !wrote {
		b.WriteString("# No deploy parameters declared.\n")
	}
	return b.String()
}

func envKey(id string) string {
	up := strings.ToUpper(id)
	var b strings.Builder
	for _, r := range up {
		switch {
		case r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return b.String()
}

func sortedKeys[T any](m map[string]T) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
