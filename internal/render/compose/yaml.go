package compose

import (
	"sort"
	"strconv"
	"strings"
)

// MarshalYAML emits deterministic Compose YAML (LF, sorted maps, no ambient interpolation).
func MarshalYAML(f File) ([]byte, error) {
	var b strings.Builder
	b.WriteString("# Generated by iacpack — derived, non-authoritative. Do not edit as source of truth.\n")
	b.WriteString("name: ")
	writeScalar(&b, f.Name)
	b.WriteByte('\n')

	if len(f.Services) > 0 {
		b.WriteString("services:\n")
		for _, id := range sortedKeys(f.Services) {
			svc := f.Services[id]
			b.WriteString("  ")
			writeKey(&b, id)
			b.WriteString(":\n")
			if err := writeService(&b, "    ", svc); err != nil {
				return nil, err
			}
		}
	}
	if len(f.Networks) > 0 {
		b.WriteString("networks:\n")
		for _, id := range sortedKeys(f.Networks) {
			n := f.Networks[id]
			b.WriteString("  ")
			writeKey(&b, id)
			b.WriteString(":\n")
			if n.External {
				b.WriteString("    external: true\n")
				if n.Name != "" {
					b.WriteString("    name: ")
					writeScalar(&b, n.Name)
					b.WriteByte('\n')
				}
			} else {
				b.WriteString("    {}\n")
			}
		}
	}
	if len(f.Volumes) > 0 {
		b.WriteString("volumes:\n")
		for _, id := range sortedKeys(f.Volumes) {
			v := f.Volumes[id]
			b.WriteString("  ")
			writeKey(&b, id)
			b.WriteString(":\n")
			if v.External {
				b.WriteString("    external: true\n")
				if v.Name != "" {
					b.WriteString("    name: ")
					writeScalar(&b, v.Name)
					b.WriteByte('\n')
				}
			} else {
				b.WriteString("    {}\n")
			}
		}
	}
	if len(f.Secrets) > 0 {
		b.WriteString("secrets:\n")
		for _, id := range sortedKeys(f.Secrets) {
			s := f.Secrets[id]
			b.WriteString("  ")
			writeKey(&b, id)
			b.WriteString(":\n")
			b.WriteString("    file: ")
			writeScalar(&b, s.File)
			b.WriteByte('\n')
		}
	}
	return []byte(b.String()), nil
}

func writeService(b *strings.Builder, ind string, svc Service) error {
	if svc.Image != "" {
		b.WriteString(ind + "image: ")
		writeScalar(b, svc.Image)
		b.WriteByte('\n')
	}
	if svc.User != "" {
		b.WriteString(ind + "user: ")
		writeScalar(b, svc.User)
		b.WriteByte('\n')
	}
	if svc.Build != nil {
		b.WriteString(ind + "build:\n")
		b.WriteString(ind + "  context: ")
		writeScalar(b, svc.Build.Context)
		b.WriteByte('\n')
		b.WriteString(ind + "  dockerfile: ")
		writeScalar(b, svc.Build.Dockerfile)
		b.WriteByte('\n')
		if len(svc.Build.Args) > 0 {
			b.WriteString(ind + "  args:\n")
			for _, k := range sortedKeys(svc.Build.Args) {
				b.WriteString(ind + "    ")
				writeKey(b, k)
				b.WriteString(": ")
				writeScalar(b, svc.Build.Args[k])
				b.WriteByte('\n')
			}
		}
	}
	if len(svc.Command) > 0 {
		writeStringSeq(b, ind, "command", svc.Command)
	}
	if svc.EntrypointClear {
		b.WriteString(ind + "entrypoint: []\n")
	} else if len(svc.Entrypoint) > 0 {
		writeStringSeq(b, ind, "entrypoint", svc.Entrypoint)
	}
	if len(svc.Environment) > 0 {
		b.WriteString(ind + "environment:\n")
		for _, k := range sortedKeys(svc.Environment) {
			b.WriteString(ind + "  ")
			writeKey(b, k)
			b.WriteString(": ")
			writeScalar(b, svc.Environment[k])
			b.WriteByte('\n')
		}
	}
	if len(svc.Ports) > 0 {
		b.WriteString(ind + "ports:\n")
		for _, p := range svc.Ports {
			b.WriteString(ind + "  - target: " + strconv.Itoa(p.Target) + "\n")
			if p.Published != "" {
				b.WriteString(ind + "    published: ")
				writeScalar(b, p.Published)
				b.WriteByte('\n')
			}
			if p.HostIP != "" {
				b.WriteString(ind + "    host_ip: ")
				writeScalar(b, p.HostIP)
				b.WriteByte('\n')
			}
			if p.Protocol != "" {
				b.WriteString(ind + "    protocol: ")
				writeScalar(b, p.Protocol)
				b.WriteByte('\n')
			}
		}
	}
	if len(svc.Networks) > 0 {
		nets := append([]string(nil), svc.Networks...)
		sort.Strings(nets)
		writeStringSeq(b, ind, "networks", nets)
	}
	if len(svc.Volumes) > 0 {
		b.WriteString(ind + "volumes:\n")
		for _, v := range svc.Volumes {
			b.WriteString(ind + "  - type: ")
			writeScalar(b, v.Type)
			b.WriteByte('\n')
			b.WriteString(ind + "    source: ")
			writeScalar(b, v.Source)
			b.WriteByte('\n')
			b.WriteString(ind + "    target: ")
			writeScalar(b, v.Target)
			b.WriteByte('\n')
			if v.ReadOnly {
				b.WriteString(ind + "    read_only: true\n")
			} else {
				// Explicit false: omit means some compose engines keep a prior RO HostConfig.
				b.WriteString(ind + "    read_only: false\n")
			}
			if v.Relabel != "" {
				b.WriteString(ind + "    bind:\n")
				b.WriteString(ind + "      selinux: ")
				writeScalar(b, v.Relabel)
				b.WriteByte('\n')
			}
		}
	}
	if len(svc.Secrets) > 0 {
		b.WriteString(ind + "secrets:\n")
		for _, s := range svc.Secrets {
			b.WriteString(ind + "  - source: ")
			writeScalar(b, s.Source)
			b.WriteByte('\n')
			b.WriteString(ind + "    target: ")
			writeScalar(b, s.Target)
			b.WriteByte('\n')
		}
	}
	if len(svc.DependsOn) > 0 {
		b.WriteString(ind + "depends_on:\n")
		for _, k := range sortedKeys(svc.DependsOn) {
			d := svc.DependsOn[k]
			b.WriteString(ind + "  ")
			writeKey(b, k)
			b.WriteString(":\n")
			b.WriteString(ind + "    condition: ")
			writeScalar(b, d.Condition)
			b.WriteByte('\n')
		}
	}
	if svc.Healthcheck != nil {
		h := svc.Healthcheck
		b.WriteString(ind + "healthcheck:\n")
		writeStringSeq(b, ind+"  ", "test", h.Test)
		if h.Interval != "" {
			b.WriteString(ind + "  interval: ")
			writeScalar(b, h.Interval)
			b.WriteByte('\n')
		}
		if h.Timeout != "" {
			b.WriteString(ind + "  timeout: ")
			writeScalar(b, h.Timeout)
			b.WriteByte('\n')
		}
		if h.StartPeriod != "" {
			b.WriteString(ind + "  start_period: ")
			writeScalar(b, h.StartPeriod)
			b.WriteByte('\n')
		}
		if h.Retries > 0 {
			b.WriteString(ind + "  retries: " + strconv.Itoa(h.Retries) + "\n")
		}
	}
	if svc.Restart != "" {
		b.WriteString(ind + "restart: ")
		writeScalar(b, svc.Restart)
		b.WriteByte('\n')
	}
	if svc.WorkingDir != "" {
		b.WriteString(ind + "working_dir: ")
		writeScalar(b, svc.WorkingDir)
		b.WriteByte('\n')
	}
	if len(svc.Profiles) > 0 {
		profs := append([]string(nil), svc.Profiles...)
		sort.Strings(profs)
		writeStringSeq(b, ind, "profiles", profs)
	}
	if len(svc.Devices) > 0 {
		devs := append([]string(nil), svc.Devices...)
		sort.Strings(devs)
		writeStringSeq(b, ind, "devices", devs)
	}
	if len(svc.SecurityOpt) > 0 {
		opts := append([]string(nil), svc.SecurityOpt...)
		sort.Strings(opts)
		writeStringSeq(b, ind, "security_opt", opts)
	}
	if svc.Deploy != nil && (svc.Deploy.CPUs != "" || svc.Deploy.Memory != "" || svc.Deploy.GPU > 0 || svc.Deploy.GPUAll) {
		b.WriteString(ind + "deploy:\n")
		b.WriteString(ind + "  resources:\n")
		if svc.Deploy.CPUs != "" || svc.Deploy.Memory != "" {
			b.WriteString(ind + "    limits:\n")
			if svc.Deploy.CPUs != "" {
				b.WriteString(ind + "      cpus: ")
				writeScalar(b, svc.Deploy.CPUs)
				b.WriteByte('\n')
			}
			if svc.Deploy.Memory != "" {
				b.WriteString(ind + "      memory: ")
				writeScalar(b, svc.Deploy.Memory)
				b.WriteByte('\n')
			}
		}
		if svc.Deploy.GPU > 0 || svc.Deploy.GPUAll {
			b.WriteString(ind + "    reservations:\n")
			b.WriteString(ind + "      devices:\n")
			b.WriteString(ind + "        - driver: nvidia\n")
			b.WriteString(ind + "          count: ")
			if svc.Deploy.GPUAll {
				b.WriteString("all")
			} else {
				b.WriteString(strconv.Itoa(svc.Deploy.GPU))
			}
			b.WriteByte('\n')
			b.WriteString(ind + "          capabilities: [gpu]\n")
		}
	}
	return nil
}

func writeStringSeq(b *strings.Builder, ind, key string, vals []string) {
	b.WriteString(ind)
	writeKey(b, key)
	b.WriteString(":\n")
	for _, v := range vals {
		b.WriteString(ind + "  - ")
		writeScalar(b, v)
		b.WriteByte('\n')
	}
}

func writeKey(b *strings.Builder, s string) {
	if needsQuote(s) {
		writeQuoted(b, s)
		return
	}
	b.WriteString(s)
}

func writeScalar(b *strings.Builder, s string) {
	if s == "" || needsQuote(s) {
		writeQuoted(b, s)
		return
	}
	b.WriteString(s)
}

func writeQuoted(b *strings.Builder, s string) {
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteByte(c)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
}

func needsQuote(s string) bool {
	if s == "" || s == "null" || s == "~" {
		return true
	}
	// YAML 1.1 bools (PyYAML / podman-compose): keep literal argv strings like "yes".
	if isYAML11BoolString(s) {
		return true
	}
	if _, err := strconv.ParseFloat(s, 64); err == nil {
		return true
	}
	for _, r := range s {
		switch r {
		case ':', '#', '{', '}', '[', ']', ',', '&', '*', '!', '|', '>', '\'', '"', '%', '@', '`', ' ', '\t':
			return true
		}
	}
	return false
}

func isYAML11BoolString(s string) bool {
	switch s {
	case "y", "Y", "yes", "Yes", "YES",
		"n", "N", "no", "No", "NO",
		"true", "True", "TRUE",
		"false", "False", "FALSE",
		"on", "On", "ON",
		"off", "Off", "OFF":
		return true
	default:
		return false
	}
}

func sortedKeys[T any](m map[string]T) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
