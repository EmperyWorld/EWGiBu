// Package secretfile writes generated secret files into a workspace secrets
// directory. Callers never receive the file bytes back through an API.
package secretfile

import (
	"crypto/rand"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
)

// Kind is the shape of a generated secret file.
type Kind string

const (
	KindPassword Kind = "password"
	KindPort     Kind = "port"
	KindName     Kind = "name"
)

const (
	passwordLen = 32
	nameLen     = 12
	portMin     = 1024
	portMax     = 65535
)

// Alphabet without I, l, O, 0, 1 and without URL delimiters.
const passwordAlphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789"

const nameFirst = "abcdefghijklmnopqrstuvwxyz"
const nameRest = nameFirst + "0123456789"

// Same identifier rule as a manifest secret id.
var idRe = regexp.MustCompile(`^[a-z][a-z0-9-]{0,62}$`)

var (
	ErrBadID   = errors.New("secret id is not a valid identifier")
	ErrBadKind = errors.New("unsupported secret kind")
	ErrExists  = errors.New("secret file already exists")
	ErrSymlink = errors.New("refusing to follow a symlink")
)

// Generate returns a new secret of kind using r as the entropy source.
// The result is for writing to disk. Do not log it or put it in a response.
func Generate(kind Kind, r io.Reader) (string, error) {
	if r == nil {
		r = rand.Reader
	}
	switch kind {
	case KindPassword:
		return randFrom(r, passwordAlphabet, passwordLen)
	case KindName:
		first, err := randFrom(r, nameFirst, 1)
		if err != nil {
			return "", err
		}
		rest, err := randFrom(r, nameRest, nameLen-1)
		if err != nil {
			return "", err
		}
		return first + rest, nil
	case KindPort:
		var buf [2]byte
		if _, err := io.ReadFull(r, buf[:]); err != nil {
			return "", err
		}
		span := portMax - portMin + 1
		n := int(buf[0])<<8 | int(buf[1])
		return fmt.Sprintf("%d", portMin+(n%span)), nil
	default:
		return "", ErrBadKind
	}
}

// Write creates workspace/secrets/<id> with mode 0600 under a 0700 directory.
// rel is the workspace-relative path. The generated bytes are not returned.
func Write(workspace, id string, kind Kind, replace bool) (string, error) {
	if !idRe.MatchString(id) {
		return "", ErrBadID
	}
	switch kind {
	case KindPassword, KindPort, KindName:
	default:
		return "", ErrBadKind
	}
	root, err := filepath.Abs(workspace)
	if err != nil {
		return "", err
	}
	root = filepath.Clean(root)
	rel := filepath.Join("secrets", id)
	dest := filepath.Join(root, rel)
	if !within(root, dest) {
		return "", ErrBadID
	}
	dir := filepath.Dir(dest)
	if err := rejectSymlink(dir); err != nil {
		return "", err
	}
	if err := rejectSymlink(dest); err != nil {
		return "", err
	}
	if _, err := os.Lstat(dest); err == nil && !replace {
		return "", ErrExists
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return "", err
	}
	raw, err := Generate(kind, rand.Reader)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	if err := os.Chmod(dir, 0o700); err != nil {
		return "", err
	}
	if replace {
		if err := (osFS{}).replace(dest, []byte(raw)); err != nil {
			return "", err
		}
	} else if err := (osFS{}).create(dest, []byte(raw)); err != nil {
		if _, statErr := os.Lstat(dest); statErr == nil {
			return "", ErrExists
		}
		return "", err
	}
	if err := os.Chmod(dest, 0o600); err != nil {
		return "", err
	}
	return filepath.ToSlash(rel), nil
}

func within(root, path string) bool {
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return false
	}
	return rel != ".." && !filepath.IsAbs(rel) && len(rel) >= 2 && rel[:2] != ".."+string(filepath.Separator) && rel != ".."
}

func rejectSymlink(path string) error {
	fi, err := os.Lstat(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return err
	}
	if fi.Mode()&os.ModeSymlink != 0 {
		return ErrSymlink
	}
	return nil
}

func randFrom(r io.Reader, alphabet string, n int) (string, error) {
	if n <= 0 || alphabet == "" || len(alphabet) > 256 {
		return "", ErrBadKind
	}
	limit := 256 - (256 % len(alphabet))
	out := make([]byte, n)
	buf := make([]byte, 1)
	for i := 0; i < n; {
		if _, err := io.ReadFull(r, buf); err != nil {
			return "", err
		}
		v := int(buf[0])
		if v >= limit {
			continue
		}
		out[i] = alphabet[v%len(alphabet)]
		i++
	}
	return string(out), nil
}

// osFS keeps filesystem writes behind a small seam so tests can still use the
// real disk. The methods match filesystem.OS without importing a cycle.
type osFS struct{}

func (osFS) create(path string, data []byte) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	_, werr := f.Write(data)
	cerr := f.Close()
	if werr != nil {
		_ = os.Remove(path)
		return werr
	}
	return cerr
}

func (osFS) replace(path string, data []byte) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".iacpack-secret-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	cleanup := true
	defer func() {
		if cleanup {
			_ = os.Remove(tmpName)
		}
	}()
	if err := tmp.Chmod(0o600); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, path); err != nil {
		return err
	}
	cleanup = false
	return nil
}
